def _normalize(name: str) -> str:
    return " ".join(name.lower().replace("ё", "е").replace(".", " ").split())


CITIES: dict[str, tuple[float, float]] = {}
for _line in _CITIES.strip().splitlines():
    *_words, _lon, _lat = _line.split()
    CITIES[_normalize(" ".join(_words))] = (float(_lon), float(_lat))

_PREFIXES = ("город ", "г ", "гор ")


def find_city(address: str) -> tuple[float, float] | None:
    """Ищет известный город среди частей адреса, разделённых запятыми:
    «Казань, Баумана 1», «г. Казань, ул. Баумана», «ул. Невская 5, Санкт-Петербург»."""
    for part in address.split(","):
        key = _normalize(part)
        for prefix in _PREFIXES:
            if key.startswith(prefix):
                key = key[len(prefix):]
        if key in CITIES:
            return CITIES[key]
    return None
